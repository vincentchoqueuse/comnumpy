"""Multipath fading: delay profiles and Doppler processes (decision D43).

The delay axis gets the treatment decisions D15/D17/D20 gave the
frequency axis: a frozen value object carrying the numbers *and* their
provenance, a registry-backed catalog of standard models, and a
self-check at construction against the figures published alongside the
table. ``CarrierType`` types the frequency axis, ``FieldRole`` the frame
axis, and :class:`PowerDelayProfile` now describes the delay axis.

A standardized channel model is a power delay profile **plus** a Doppler
spectrum; both live here. The taps are generated by
:func:`rayleigh_process`, and applied to a signal by
:class:`~comnumpy.core.channels.TappedDelayLineChannel`.
"""
from __future__ import annotations

import logging

from dataclasses import dataclass, field
from enum import Enum
from typing import Any, Callable, Optional

import numpy as np

from comnumpy.exceptions import ShapeError

logger = logging.getLogger(__name__)

